"""Render retrieval results as a Markdown table and a bar chart."""

from collections.abc import Sequence
from pathlib import Path

from opspilot.evals.retrieval import LATENCY_BUDGET_MS, ConfigResult

# Categorical slots 1-3 of the reference data-viz palette (validated all-pairs, light mode).
MODE_COLORS = {"dense": "#2a78d6", "keyword": "#eb6834", "hybrid": "#1baf7a"}
SURFACE = "#fcfcfb"
TEXT_PRIMARY = "#0b0b0b"
TEXT_SECONDARY = "#52514e"
GRID = "#e4e3df"


def _mode(r: ConfigResult) -> str:
    c = r.config
    return f"hybrid α={c.alpha:g}" if c.mode == "hybrid" else c.mode  # noqa: RUF001


def render_markdown(
    results: Sequence[ConfigResult], default: ConfigResult | None, meta: dict[str, object]
) -> str:
    """The RESULTS.md document: setup, full matrix, default choice and per-type breakdown."""
    lines = [
        "# Retrieval evaluation results",
        "",
        f"Generated by `opspilot eval retrieval --configs all` on {meta['date']} "
        f"({meta['machine']}).",
        f"{meta['queries']} queries (40 symptom, 10 log snippet, 10 hard near-distractor) over "
        f"{meta['documents']} documents. Embeddings: `{meta['embedding_model']}`; reranker: "
        f"`{meta['reranker_model']}` over the top 20 candidates.",
        "",
        "Metrics are computed on the ranked list of distinct documents. Recall@k and MRR@10 "
        "use the single primary document of each query; nDCG@5 uses graded relevance "
        "(primary = 2, secondary = 1). Latency is end-to-end `Retriever.retrieve` time "
        "including query embedding and reranking, measured on this laptop after one "
        "warm-up query.",
        "",
        "| store | chunker | mode | rerank | R@1 | R@3 | R@5 | MRR@10 | nDCG@5 | p50 ms | p95 ms |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(results, key=lambda x: -x.ndcg_at_5):
        c = r.config
        star = " **(default)**" if default and r.label == default.label else ""
        lines.append(
            f"| {c.store} | {c.chunker} | {_mode(r)}{star} | {'on' if c.rerank else 'off'} "
            f"| {r.recall_at_1:.3f} | {r.recall_at_3:.3f} | {r.recall_at_5:.3f} "
            f"| {r.mrr_at_10:.3f} | {r.ndcg_at_5:.3f} | {r.p50_ms:.0f} | {r.p95_ms:.0f} |"
        )
    lines += ["", "## Default configuration", ""]
    if default:
        lines.append(
            f"Best nDCG@5 with p95 under {LATENCY_BUDGET_MS:.0f} ms: **{default.label}** "
            f"(nDCG@5 {default.ndcg_at_5:.3f}, R@5 {default.recall_at_5:.3f}, "
            f"p95 {default.p95_ms:.0f} ms). See ADR-0004."
        )
    else:
        lines.append(f"No configuration met the {LATENCY_BUDGET_MS:.0f} ms p95 budget.")
    lines += [
        "",
        "## By query type (nDCG@5)",
        "",
        "| config | symptom | log | hard |",
        "|---|---|---|---|",
    ]
    for r in sorted(results, key=lambda x: -x.ndcg_at_5):
        t = r.by_type
        lines.append(
            f"| {r.label} | {t.get('symptom', {}).get('ndcg_at_5', 0):.3f} "
            f"| {t.get('log', {}).get('ndcg_at_5', 0):.3f} "
            f"| {t.get('hard', {}).get('ndcg_at_5', 0):.3f} |"
        )
    lines += ["", "![nDCG@5 by configuration](retrieval_ndcg.png)", ""]
    return "\n".join(lines)


def render_chart(results: Sequence[ConfigResult], default: ConfigResult | None, path: Path) -> None:
    """Horizontal bars of nDCG@5 per configuration, coloured by search mode."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch

    ordered = sorted(results, key=lambda r: r.ndcg_at_5)
    height = 0.3 * len(ordered) + 1.4
    fig, ax = plt.subplots(figsize=(9, height), dpi=150)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    y = range(len(ordered))
    values = [r.ndcg_at_5 for r in ordered]
    colors = [MODE_COLORS[r.config.mode] for r in ordered]
    ax.barh(list(y), values, height=0.72, color=colors, edgecolor=SURFACE, linewidth=2)
    for i, r in enumerate(ordered):
        ax.text(
            r.ndcg_at_5 + 0.005,
            i,
            f"{r.ndcg_at_5:.3f}",
            va="center",
            fontsize=7,
            color=TEXT_SECONDARY,
        )
    labels = [
        r.label + ("  (default)" if default and r.label == default.label else "") for r in ordered
    ]
    ax.set_yticks(list(y), labels, fontsize=7, color=TEXT_PRIMARY)
    ax.set_xlim(0, 1.05)
    ax.set_xlabel("nDCG@5", color=TEXT_SECONDARY, fontsize=8)
    ax.tick_params(axis="x", colors=TEXT_SECONDARY, labelsize=7)
    ax.tick_params(axis="y", length=0)
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.set_title(
        "Retrieval quality by configuration (60 queries)",
        loc="left",
        fontsize=10,
        color=TEXT_PRIMARY,
    )
    ax.legend(
        handles=[Patch(color=c, label=m) for m, c in MODE_COLORS.items()],
        loc="lower right",
        fontsize=7,
        frameon=False,
        labelcolor=TEXT_SECONDARY,
    )
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)
